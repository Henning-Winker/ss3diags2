test_that("growth and ridge plots build", {
  data(ss3ank, package = "ss3diags2", envir = environment())
  lfd <- ss3_lencomp(ss3ank); fit <- ss3_lencomp(ss3ank, what = "exp"); lh <- ss3_lhpar(ss3ank)
  g <- ss3plot_growth(ss3ank, lfd = lfd)
  expect_silent(ggplot2::ggplot_build(g))
  expect_equal(sort(unique(g$data$unit)), c("F", "M"))
  expect_silent(ggplot2::ggplot_build(ss3plot_growth(lh)))
  for(ty in c("obs", "exp", "both"))
    expect_silent(ggplot2::ggplot_build(ss3plot_ridges(lfd["FR_IE_IBTS"], fit = fit["FR_IE_IBTS"], type = ty, lhpar = lh)))
  expect_error(ss3plot_ridges(lfd, type = "both"), "fit")
  skip_no_data(); e <- load_ss3("pac.hke")
  expect_silent(ggplot2::ggplot_build(ss3plot_ridges(ss3_agecomp(e$ss3phk), type = "obs")))
})
