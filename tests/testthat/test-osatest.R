test_that("OSA residual tests, test shading, QQ envelopes and the scorecard", {
  data(ss3simple, package = "ss3diags2", envir = environment())
  r <- ss3_resid(ss3simple)
  ot <- ss3_osatest(r, nsim = 99)
  expect_true(all(c("N", "mean", "SD", "QQ RMSE", "AD", "p", "result", "outside 1.96 (%)") %in% names(ot)))
  expect_true(all(ot$result %in% c("PASS", "FAIL")))
  expect_true(all(ot$p > 0 & ot$p <= 1))
  # AD statistic: a standard normal sample is small, a shifted one large
  set.seed(2); z <- rnorm(200)
  expect_lt(ss3diags2:::.ad_stat(z), 2.5); expect_gt(ss3diags2:::.ad_stat(z + 1), 10)
  env <- ss3diags2:::.qq_envelope(50)
  expect_true(all(env$lo < env$theo & env$theo < env$hi))
  expect_s3_class(ss3plot_resid(r, test = TRUE, nsim = 49), "ggplot")
  expect_s3_class(ss3plot_resid(r, type = "qq", test = TRUE, nsim = 49), "ggplot")
  expect_s3_class(ss3plot_resid(r, type = "len", test = TRUE, nsim = 49), "ggplot")
  data(ss3sma, package = "ss3diags2", envir = environment()); data(retro.sma, package = "ss3diags2", envir = environment())
  sc <- ss3_scorecard(list(sma = ss3sma), retro = list(sma = retro.sma), nsim = 49)
  expect_true(all(c("Retro SSB rho", "Forecast SSB rho") %in% names(sc$table)))
  expect_true(any(grepl("^Runs index", names(sc$table))) && any(grepl("^MASE index", names(sc$table))))
  expect_true(all(unlist(sc$table[, -1]) %in% c(0L, 1L, NA)))
  expect_s3_class(ss3plot_scorecard(sc), "ggplot")
})
