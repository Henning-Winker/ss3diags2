test_that("Mohn's rho, MASE and runs tests reproduce ss3diags", {
  skip_no_data(); skip_if_not_installed("r4ss"); skip_if_not_installed("mvtnorm")
  e <- load_ss3("natl.sma")
  st <- ss3_retro(e$retro.sma)
  expect_s4_class(st, "FLStocks"); expect_equal(names(st), as.character(2015:2010))
  sm <- r4ss::SSsummarize(e$retro.sma, verbose = FALSE)
  o <- ss3diags::SShcbias(sm, verbose = FALSE)
  a <- ss3_mohn(st, c("SSB", "F/Ftgt"))                 # sma reports F as F/Fmsy
  expect_equal(a$rho, o$Rho, tolerance = 1e-6); expect_equal(a$fcrho, o$ForcastRho, tolerance = 1e-6)
  h <- ss3_hindcast(e$retro.sma); om <- ss3diags::SSmase(sm, verbose = FALSE)
  expect_equal(h$mase$MASE, om$MASE, tolerance = 1e-6); expect_equal(h$mase$n.eval, om$n.eval)
  r <- ss3_runs(e$ss3sma); ro <- ss3diags::SSrunstest(e$ss3sma, verbose = FALSE)
  expect_equal(r$runs.p, ro$runs.p); expect_equal(r$sigma3.lo, ro$sigma3.lo, tolerance = 1e-6)
  rl <- ss3_runs(e$ss3sma, quant = "len"); rol <- ss3diags::SSrunstest(e$ss3sma, quants = "len", verbose = FALSE)
  expect_equal(rl$runs.p, rol$runs.p); expect_equal(rl$sigma3.hi, rol$sigma3.hi, tolerance = 1e-6)
})

test_that("diagnostic plots build", {
  skip_no_data(); skip_if_not_installed("mvtnorm")
  e <- load_ss3("pac.hke")
  st <- ss3_retro(e$retro.phk)
  expect_silent(ggplot2::ggplot_build(ss3plot_retro(st)))
  expect_silent(ggplot2::ggplot_build(ss3plot_hcxval(ss3_hindcast(e$retro.phk))))
  expect_silent(ggplot2::ggplot_build(ss3plot_runs(e$ss3phk)))
  p <- ss3plot_jres(e$ss3phk); expect_silent(suppressWarnings(ggplot2::ggplot_build(p)))
  expect_true("Combined" %in% attr(p, "rmse")$index)
  pra <- readRDS(system.file("extdata", "pra.27.3a4a", "pra.27.3a4a.rds", package = "ss3diags2"))
  expect_silent(ggplot2::ggplot_build(ss3plot_runs(pra)))
})
